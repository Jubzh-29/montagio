/**
 * The pinned versions (infra/runpod/versions.env, shared with the GPU pod
 * bootstrap) and the weights of registry/models.lock.yaml, read without any
 * npm package: the installer runs on bare Node, before `npm ci`.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export type TorchPin = { torch: string; torchvision: string; cuda: string; minDriverCuda: [number, number] };

export type Versions = {
  comfyuiRepo: string;
  comfyuiTag: string;
  comfyuiCommit: string;
  proxyVersion: string;
  torch: TorchPin;
  torchFallback: TorchPin;
};

/** `folder` is relative to ComfyUI's models/; `extension` is null for the weights of the camera presets. */
export type LockWeight = { id: string; file: string; url: string; sha256: string; size: number; folder: string; extension: string | null };

/** ComfyUI models/ folders a lock file can go to (the same set as infra/runpod/lib/weights.ts); `tts` holds the voice packs. */
const COMFY_FOLDERS = new Set([
  'checkpoints',
  'diffusion_models',
  'text_encoders',
  'vae',
  'loras',
  'clip_vision',
  'controlnet',
  'upscale_models',
  'audio_encoders',
  'tts',
]);

export function parseVersionsEnv(text: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq > 0) values[line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
  }
  return values;
}

/** "cu130" → [13, 0], "cu128" → [12, 8]: the lowest CUDA version the driver must report. */
function driverCudaOf(flavor: string): [number, number] {
  const digits = /^cu(\d+)(\d)$/.exec(flavor);
  if (!digits) throw new Error(`versions.env: cannot read the CUDA version of "${flavor}"`);
  return [Number(digits[1]), Number(digits[2])];
}

export function versionsFrom(env: Record<string, string>): Versions {
  const get = (key: string): string => {
    const value = env[key];
    if (!value) throw new Error(`infra/runpod/versions.env has no ${key}`);
    return value;
  };
  const pin = (torch: string, vision: string, cuda: string): TorchPin => ({
    torch: get(torch),
    torchvision: get(vision),
    cuda: get(cuda),
    minDriverCuda: driverCudaOf(get(cuda)),
  });
  return {
    comfyuiRepo: get('COMFYUI_REPO'),
    comfyuiTag: get('COMFYUI_TAG'),
    comfyuiCommit: get('COMFYUI_COMMIT'),
    proxyVersion: get('COMFY_API_PROXY_VERSION'),
    torch: pin('TORCH_VERSION', 'TORCHVISION_VERSION', 'TORCH_CUDA'),
    torchFallback: pin('TORCH_FALLBACK_VERSION', 'TORCHVISION_FALLBACK_VERSION', 'TORCH_FALLBACK_CUDA'),
  };
}

export function readVersions(repoRoot: string): Versions {
  return versionsFrom(parseVersionsEnv(readFileSync(join(repoRoot, 'infra', 'runpod', 'versions.env'), 'utf8')));
}

/** A plain YAML scalar: unquoted, or in single or double quotes, with a trailing comment removed. */
function scalar(raw: string): string {
  const value = raw.trim();
  const quoted = /^(['"])(.*)\1$/.exec(value);
  if (quoted) return quoted[2]!;
  return value.replace(/\s+#.*$/, '');
}

/**
 * The weights of the lock. The lock is generated by tooling with one flat
 * entry per weight (`  - id: …` then `    key: value` lines); the parity test
 * compares this reader with @montagio/registry's parseLock.
 */
export function parseLockWeights(text: string): LockWeight[] {
  const entries: Record<string, string>[] = [];
  let inWeights = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^\S/.test(line)) {
      inWeights = /^weights:\s*$/.test(line);
      continue;
    }
    if (!inWeights) continue;
    const item = /^\s*-\s+([A-Za-z0-9_]+):(.*)$/.exec(line);
    const field = /^\s+([A-Za-z0-9_]+):(.*)$/.exec(line);
    if (item) entries.push({ [item[1]!]: scalar(item[2]!) });
    else if (field && entries.length > 0) entries.at(-1)![field[1]!] = scalar(field[2]!);
  }
  return entries.map((entry) => {
    const id = entry.id ?? '?';
    for (const key of ['file', 'url', 'sha256', 'size']) {
      if (!entry[key]) throw new Error(`lock entry ${id} has no ${key}: the installer only downloads pinned files`);
    }
    const size = Number(entry.size);
    if (!Number.isSafeInteger(size) || size <= 0) throw new Error(`lock entry ${id} has an invalid size ${entry.size}`);
    let folder: string;
    if (entry.folder) {
      // the registry's rule: "/"-separated names of letters, digits, ".", "_" and "-" (no "\", which Windows reads as a separator)
      const parts = entry.folder.split('/');
      if (!COMFY_FOLDERS.has(parts[0]!) || parts.some((part) => !/^[A-Za-z0-9._-]+$/.test(part) || part === '.' || part === '..')) {
        throw new Error(`lock entry ${id}: folder "${entry.folder}" is not a path under a ComfyUI models/ folder`);
      }
      folder = entry.folder;
    } else {
      folder = new URL(entry.url!).pathname.split('/').at(-2) ?? '';
      if (!COMFY_FOLDERS.has(folder)) throw new Error(`lock entry ${id}: ${entry.url} names no ComfyUI folder (…/<folder>/<file>)`);
    }
    return { id, file: entry.file!, url: entry.url!, sha256: entry.sha256!, size, folder, extension: entry.extension || null };
  });
}

/** One extension of registry/extensions.yaml: its id, priority, requirements, and the day a GPU session validated it. */
export type ExtensionPin = { id: string; priority: number; requires: string[]; gpuValidated: string | null };

/**
 * registry/extensions.yaml, kept in block style (`  - id: …` then `    key: value`)
 * like the lock; the parity test compares this reader with @montagio/registry's.
 */
export function parseExtensionsConfig(text: string): ExtensionPin[] {
  const entries: Record<string, string>[] = [];
  let inList = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^\S/.test(line)) {
      inList = /^extensions:\s*$/.test(line);
      continue;
    }
    if (!inList) continue;
    const item = /^\s*-\s+([A-Za-z0-9_]+):(.*)$/.exec(line);
    const field = /^\s+([A-Za-z0-9_]+):(.*)$/.exec(line);
    if (item) entries.push({ [item[1]!]: scalar(item[2]!) });
    else if (field && entries.length > 0) entries.at(-1)![field[1]!] = scalar(field[2]!);
  }
  return entries.map((entry) => {
    const id = entry.id ?? '?';
    // an inline list: "[edit]", "[edit, music]"; this reader would see a block list (`requires:`
    // then `- edit` lines) as no requirement at all, so anything else is refused
    const inline = /^\[(.*)\]$/.exec(entry.requires ?? '[]');
    if (!inline) throw new Error(`registry/extensions.yaml: extension ${id}: requires must be an inline list such as [edit], not "${entry.requires}"`);
    return {
      id,
      priority: Number(entry.priority),
      requires: inline[1]!
        .split(',')
        .map((required) => required.trim())
        .filter(Boolean),
      gpuValidated: !entry.gpu_validated || entry.gpu_validated === 'null' ? null : entry.gpu_validated,
    };
  });
}

/** The extensions of the repository; none when it has no registry/extensions.yaml. */
export function readExtensions(repoRoot: string): ExtensionPin[] {
  let text: string;
  try {
    text = readFileSync(join(repoRoot, 'registry', 'extensions.yaml'), 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
  return parseExtensionsConfig(text);
}

/**
 * The extensions whose weights to install, by priority; the same rule as the app's
 * (enabledExtensions of @montagio/registry): unset, empty or "validated" keeps those a GPU
 * session validated, "all", "none", or a comma-separated list of ids.
 */
export function selectExtensions(config: ExtensionPin[], flag: string | null | undefined): string[] {
  const byPriority = [...config].sort((a, b) => a.priority - b.priority);
  const value = flag?.trim() ?? '';
  if (value === '' || value === 'validated') {
    const kept = new Set(byPriority.filter((e) => e.gpuValidated !== null).map((e) => e.id));
    for (let changed = true; changed; ) {
      changed = false;
      for (const e of byPriority) {
        if (kept.has(e.id) && !e.requires.every((id) => kept.has(id))) changed = kept.delete(e.id);
      }
    }
    return byPriority.filter((e) => kept.has(e.id)).map((e) => e.id);
  }
  if (value === 'all') return byPriority.map((e) => e.id);
  if (value === 'none') return [];
  const asked = value
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);
  const known = byPriority.map((e) => e.id);
  const unknown = asked.filter((id) => !known.includes(id));
  if (unknown.length > 0) {
    throw new Error(`--extensions: unknown extension ${unknown.map((id) => JSON.stringify(id)).join(', ')} (expected validated, all, none or a list of ${known.join(', ')})`);
  }
  for (const e of byPriority.filter((entry) => asked.includes(entry.id))) {
    const missing = e.requires.filter((id) => !asked.includes(id));
    if (missing.length > 0) throw new Error(`--extensions: ${e.id} requires ${missing.join(', ')}; add ${missing.length > 1 ? 'them' : 'it'} to the list`);
  }
  return known.filter((id) => asked.includes(id));
}

/**
 * What a plain `install` (no --extensions, no MONTAGIO_EXTENSIONS) fetches besides the camera presets: the
 * effects pack, the most shareable extension and one of the lightest (about 21 GB), once a GPU session
 * validated it. The seven together weigh about 114 GB more; `--extensions all` (or `validated`) takes them.
 */
export const INSTALL_DEFAULT_EXTENSIONS: readonly string[] = ['effects'];

export function installDefaultExtensions(config: ExtensionPin[]): string[] {
  return selectExtensions(config, 'validated').filter((id) => INSTALL_DEFAULT_EXTENSIONS.includes(id));
}

/** The weights of the camera presets, plus those of the extensions in `enabled`. */
export function weightsFor(lock: LockWeight[], enabled: readonly string[]): LockWeight[] {
  return lock.filter((weight) => !weight.extension || enabled.includes(weight.extension));
}

export function readLock(repoRoot: string): LockWeight[] {
  return parseLockWeights(readFileSync(join(repoRoot, 'registry', 'models.lock.yaml'), 'utf8'));
}
