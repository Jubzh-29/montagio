import { segmentWords, type CaptionLine } from './segment';
import { CAPTION_STYLES, type CaptionStyle, type CaptionStyleId } from './styles';
import type { CaptionTrack, CaptionWord } from './types';

/** The version of this writer: a recipe names it, since another version would draw the same words differently. */
export const ASS_GENERATOR = 'montagio/captions-ass@1';

const WIDTH = 1080;
const HEIGHT = 1920;
/** The baseline of the captions at 76 % of the height: under a 16:9 picture centred in the frame (it ends at 66 %), over the bottom bar of TikTok and Reels. */
const MARGIN_V = Math.round(HEIGHT * 0.24);
const MARGIN_H = 70;

// ASS colours are &HAABBGGRR (alpha first, 00 = opaque); inline \c tags take &HBBGGRR&.
const WHITE = '&H00FFFFFF';
const BLACK = '&H00000000';
const YELLOW = '&H0015CCFA'; // #FACC15, the karaoke preset's highlight
const LIGHT_GREY = '&H00E6E6E6';
const LIME = '&H45F7A2&'; // #A2F745, the app's accent
const CYAN = '&HFFFF00&'; // #00FFFF, the neon preset's colour
const INLINE_WHITE = '&HFFFFFF&';

/** A word as plain text: braces and backslashes would open tags, so they become their full-width look-alikes; a line break becomes a space. */
export function escapeAssText(text: string): string {
  return text.replace(/\\/g, '＼').replace(/\{/g, '｛').replace(/\}/g, '｝').replace(/[\r\n]+/g, ' ');
}

const cs = (seconds: number) => Math.max(0, Math.round(seconds * 100));

function time(seconds: number): string {
  const total = cs(seconds);
  const h = Math.floor(total / 360000);
  const m = Math.floor((total % 360000) / 6000);
  const s = Math.floor((total % 6000) / 100);
  return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(total % 100).padStart(2, '0')}`;
}

type StyleRow = { primary: string; secondary: string; outlineColour: string; back: string; borderStyle: 1 | 3; outline: number; shadow: number; spacing: number };

const ROWS: Record<CaptionStyleId, StyleRow> = {
  karaoke: { primary: YELLOW, secondary: LIGHT_GREY, outlineColour: BLACK, back: '&H80000000', borderStyle: 1, outline: 5, shadow: 2, spacing: 0 },
  pop: { primary: WHITE, secondary: WHITE, outlineColour: BLACK, back: '&H80000000', borderStyle: 1, outline: 7, shadow: 0, spacing: 1 },
  word: { primary: WHITE, secondary: WHITE, outlineColour: BLACK, back: '&H80000000', borderStyle: 1, outline: 8, shadow: 3, spacing: 2 },
  // BorderStyle 3: an opaque box in the outline colour, the outline width as its padding; 0x99 = 40 % opaque, the classic preset's backgroundOpacity.
  classic: { primary: WHITE, secondary: WHITE, outlineColour: '&H99000000', back: '&H99000000', borderStyle: 3, outline: 18, shadow: 0, spacing: 0 },
  neon: { primary: '&H00FFFF00', secondary: '&H00FFFF00', outlineColour: '&H00440000', back: '&H00000000', borderStyle: 1, outline: 2, shadow: 0, spacing: 2 },
};

function header(style: CaptionStyle): string {
  const row = ROWS[style.id];
  const bold = style.font.bold ? -1 : 0;
  return [
    '[Script Info]',
    `; Script generated by ${ASS_GENERATOR}`,
    'ScriptType: v4.00+',
    `PlayResX: ${WIDTH}`,
    `PlayResY: ${HEIGHT}`,
    'WrapStyle: 0',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: ${style.id},${style.font.family},${style.size},${row.primary},${row.secondary},${row.outlineColour},${row.back},${bold},0,0,0,100,100,${row.spacing},0,${row.borderStyle},${row.outline},${row.shadow},2,${MARGIN_H},${MARGIN_H},${MARGIN_V},1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ].join('\n');
}

const dialogue = (layer: number, start: number, end: number, style: CaptionStyleId, text: string) =>
  `Dialogue: ${layer},${time(start)},${time(end)},${style},,0,0,0,,${text}`;

/** Each word of a line said in turn: [from, to] of its event, the line drawn with that word lit (pop, neon). */
function perWord(line: CaptionLine): { lit: number; from: number; to: number }[] {
  return line.words.map((word, index) => ({
    lit: index,
    from: index === 0 ? line.start : word.start,
    to: index === line.words.length - 1 ? line.end : line.words[index + 1]!.start,
  }));
}

/** The karaoke sweep: \kf fills each word for as long as it is said, \k waits through a silence. */
function karaokeText(line: CaptionLine, label: (word: CaptionWord) => string): string {
  let cursor = cs(line.start);
  return line.words
    .map((word, index) => {
      const start = cs(word.start);
      const end = Math.max(cs(word.end), start);
      const wait = start > cursor ? `{\\k${start - cursor}}` : '';
      const fill = `{\\kf${end - Math.max(cursor, start)}}`;
      cursor = Math.max(end, cursor);
      return `${wait}${fill}${label(word)}${index < line.words.length - 1 ? ' ' : ''}`;
    })
    .join('');
}

/** Two lines at most: a break at the space nearest the middle once the text passes half of the line's characters. */
function twoLines(text: string, maxChars: number): string {
  if (text.length <= maxChars / 2) return text;
  const middle = text.length / 2;
  let best = -1;
  for (let index = 0; index < text.length; index++) {
    if (text[index] === ' ' && (best < 0 || Math.abs(index - middle) < Math.abs(best - middle))) best = index;
  }
  return best < 0 ? text : `${text.slice(0, best)}\\N${text.slice(best + 1)}`;
}

const POP_IN = '\\t(0,80,\\fscx112\\fscy112)\\t(80,160,\\fscx100\\fscy100)';

function events(style: CaptionStyle, lines: CaptionLine[], label: (word: CaptionWord) => string): string[] {
  const id = style.id;
  switch (id) {
    case 'karaoke':
      return lines.map((line) => dialogue(0, line.start, line.end, id, `{\\fad(120,120)}${karaokeText(line, label)}`));
    case 'pop':
      return lines.flatMap((line) =>
        perWord(line).map(({ lit, from, to }) => {
          const first = lit === 0;
          const text = line.words
            .map((word, index) => {
              if (index !== lit) return label(word);
              // The word said grows and turns lime; past it, white at 100 %, the line's pop-in given again (its times count from the event's start).
              const on = first ? `{\\c${LIME}\\t(0,80,\\fscx121\\fscy121)\\t(80,160,\\fscx108\\fscy108)}` : `{\\c${LIME}\\fscx108\\fscy108}`;
              const off = `{\\c${INLINE_WHITE}\\fscx100\\fscy100${first ? POP_IN : ''}}`;
              return `${on}${label(word)}${index < line.words.length - 1 ? off : ''}`;
            })
            .join(' ');
          return dialogue(0, from, to, id, `${first ? `{${POP_IN}}` : ''}${text}`);
        }),
      );
    case 'word':
      return lines.map((line) => dialogue(0, line.start, line.end, id, `{\\fscx180\\fscy180\\t(0,120,\\fscx100\\fscy100)}${line.words.map(label).join(' ')}`));
    case 'classic':
      return lines.map((line) => dialogue(0, line.start, line.end, id, `{\\fad(150,150)}${twoLines(line.words.map(label).join(' '), style.rules.maxChars)}`));
    case 'neon':
      return lines.flatMap((line) => {
        const steps = perWord(line);
        return steps.flatMap(({ lit, from, to }, index) => {
          const fade = `\\fad(${index === 0 ? 120 : 0},${index === steps.length - 1 ? 120 : 0})`;
          const glow = line.words.map((word, n) => (n === lit ? `{\\blur14\\bord9}${label(word)}{\\blur8\\bord6}` : label(word))).join(' ');
          const core = line.words.map((word, n) => (n === lit ? `{\\c${INLINE_WHITE}}${label(word)}{\\c${CYAN}}` : label(word))).join(' ');
          return [
            dialogue(0, from, to, id, `{${fade}\\blur8\\bord6\\1c${CYAN}\\3c${CYAN}}${glow}`),
            dialogue(1, from, to, id, `{${fade}\\blur1}${core}`),
          ];
        });
      });
  }
}

/** The ASS script of a track in a style, for a 1080x1920 frame (libass scales it to any other size). */
export function buildAss(track: CaptionTrack, styleId: CaptionStyleId): string {
  const style = CAPTION_STYLES[styleId];
  const label = (word: CaptionWord) => escapeAssText(style.uppercase ? word.text.toLocaleUpperCase(track.language) : word.text);
  const lines = segmentWords(track.words, style.rules);
  return [header(style), ...events(style, lines, label), ''].join('\n');
}
