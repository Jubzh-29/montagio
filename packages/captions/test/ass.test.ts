import { ASS_GENERATOR, buildAss, CAPTION_STYLE_IDS, CAPTION_STYLES, escapeAssText, isCaptionStyle, textWidth, type CaptionTrack } from '../src';

const track: CaptionTrack = {
  language: 'en',
  words: [
    { text: 'Hello,', start: 0, end: 0.68 },
    { text: 'this', start: 0.68, end: 0.86 },
    { text: 'is', start: 0.86, end: 1.02 },
    { text: 'a', start: 1.02, end: 1.12 },
    { text: 'test.', start: 1.3, end: 1.6 },
  ],
};

const dialogues = (ass: string) => ass.split('\n').filter((line) => line.startsWith('Dialogue:'));
const styleLine = (ass: string) => ass.split('\n').find((line) => line.startsWith('Style:'))!.split(',');

describe('styles', () => {
  it('offers five styles, in order', () => {
    expect(CAPTION_STYLE_IDS).toEqual(['karaoke', 'pop', 'word', 'classic', 'neon']);
    expect(isCaptionStyle('pop')).toBe(true);
    expect(isCaptionStyle('glitch')).toBe(false);
    expect(isCaptionStyle(undefined)).toBe(false);
  });
});

describe('buildAss', () => {
  it('writes a 1080x1920 script that names its generator', () => {
    const ass = buildAss(track, 'karaoke');
    expect(ass).toContain(`; Script generated by ${ASS_GENERATOR}`);
    for (const line of ['PlayResX: 1080', 'PlayResY: 1920', 'WrapStyle: 0', 'ScaledBorderAndShadow: yes']) expect(ass).toContain(line);
  });

  it('uses each style font, bold only for the fonts drawn bold', () => {
    for (const id of CAPTION_STYLE_IDS) {
      const fields = styleLine(buildAss(track, id));
      expect(fields[1]).toBe(CAPTION_STYLES[id].font.family);
      expect(fields[7]).toBe(CAPTION_STYLES[id].font.bold ? '-1' : '0');
    }
    expect(CAPTION_STYLES.karaoke.font.family).toBe('Poppins');
    expect(CAPTION_STYLES.classic.font.family).toBe('Montserrat');
    expect(CAPTION_STYLES.pop.font.family).toBe('Anton');
    expect(CAPTION_STYLES.word.font.family).toBe('Bebas Neue');
  });

  it('karaoke: one line per event, each word filled for as long as it is said, yellow over light grey', () => {
    const ass = buildAss(track, 'karaoke');
    const fields = styleLine(ass);
    expect(fields[3]).toBe('&H0015CCFA');
    expect(fields[4]).toBe('&H00E6E6E6');
    const events = dialogues(ass);
    expect(events).toHaveLength(2); // 18 characters at most: "Hello, this is a", then "test."
    expect(events[0]).toContain('0:00:00.00,0:00:01.30');
    expect(events[0]).toContain('{\\fad(120,120)}{\\kf68}Hello, {\\kf18}this {\\kf16}is {\\kf10}a');
    expect(events[1]).toContain('0:00:01.30,0:00:01.90');
    // a silence between two words of a line is a \k with no text
    const paused = buildAss({ language: 'en', words: [track.words[0]!, { text: 'there', start: 1, end: 1.4 }] }, 'karaoke');
    expect(dialogues(paused)[0]).toContain('{\\kf68}Hello, {\\k32}{\\kf40}there');
  });

  it('pop: capitals, the word said in lime and a little larger, the line popping in', () => {
    const events = dialogues(buildAss(track, 'pop'));
    expect(events[0]).toContain('\\t(0,80,\\fscx112\\fscy112)\\t(80,160,\\fscx100\\fscy100)');
    expect(events[0]).toContain('{\\c&H45F7A2&\\t(0,80,\\fscx121\\fscy121)\\t(80,160,\\fscx108\\fscy108)}HELLO,');
    expect(events[1]).toContain('HELLO, {\\c&H45F7A2&\\fscx108\\fscy108}THIS{\\c&HFFFFFF&\\fscx100\\fscy100} IS');
    // one event per word, end to end
    expect(events[0]).toContain('0:00:00.00,0:00:00.68');
    expect(events[1]).toContain('0:00:00.68,0:00:00.86');
  });

  it('word: one word at a time, in capitals, stamped down', () => {
    const events = dialogues(buildAss(track, 'word'));
    expect(events).toHaveLength(5);
    expect(events[0]).toContain('{\\fscx180\\fscy180\\t(0,120,\\fscx100\\fscy100)}HELLO,');
  });

  it('classic: a translucent box, a fade, two lines at most', () => {
    const fields = styleLine(buildAss(track, 'classic'));
    expect(fields[15]).toBe('3');
    expect(fields[6]).toBe('&H99000000');
    const long = 'This sentence is long enough to need a second line'.split(' ').map((text, index) => ({ text, start: index * 0.3, end: index * 0.3 + 0.3 }));
    const events = dialogues(buildAss({ language: 'en', words: long }, 'classic'));
    expect(events[0]).toContain('{\\fad(150,150)');
    for (const event of events) expect(event.split('\\N').length).toBeLessThanOrEqual(2);
    expect(events.some((event) => event.includes('\\N'))).toBe(true);
  });

  it('neon: a blurred cyan glow under the text, the word said in white', () => {
    const events = dialogues(buildAss(track, 'neon'));
    expect(events.filter((event) => event.startsWith('Dialogue: 0,'))).not.toHaveLength(0);
    expect(events.filter((event) => event.startsWith('Dialogue: 1,'))).not.toHaveLength(0);
    expect(events.find((event) => event.startsWith('Dialogue: 0,'))).toContain('\\blur8');
    expect(events.find((event) => event.startsWith('Dialogue: 1,'))).toContain('{\\c&HFFFFFF&}HELLO,{\\c&HFFFF00&}');
  });

  it('writes no event for no words, and the same script for the same input', () => {
    expect(dialogues(buildAss({ language: 'en', words: [] }, 'pop'))).toEqual([]);
    expect(buildAss(track, 'neon')).toBe(buildAss(structuredClone(track), 'neon'));
  });

  it('turns no word into a tag', () => {
    const ass = buildAss({ language: 'en', words: [{ text: '{\\pos(0,0)}', start: 0, end: 1 }] }, 'classic');
    expect(dialogues(ass)[0]).not.toContain('{\\pos');
    expect(dialogues(ass)[0]).toContain('｛＼pos(0,0)｝');
  });

  it('upper-cases in the language of the track', () => {
    const ass = buildAss({ language: 'tr', words: [{ text: 'istanbul', start: 0, end: 1 }] }, 'word');
    expect(dialogues(ass)[0]).toContain('İSTANBUL');
  });
});

describe('escapeAssText', () => {
  it('leaves no brace, no backslash and no line break', () => {
    const escaped = escapeAssText('a{b}\\c\nd');
    expect(escaped).not.toMatch(/[{}\\\n]/);
    expect(escaped).toBe('a｛b｝＼c d');
  });

  it('drops control characters and turns the Unicode line separators into spaces', () => {
    expect(escapeAssText('a\u0000b\u0007c\u2028d\u0085e')).toBe('abc de');
  });
});

describe('the frame', () => {
  const LONG = { language: 'de', words: [{ text: 'Geschwindigkeitsbegrenzung', start: 0, end: 1.2 }] };
  /** The scale a dialogue's text is drawn at: its last \fscx, in hundredths. */
  const lastScale = (event: string) => Number([...event.matchAll(/\\fscx(\d+)/g)].at(-1)![1]) / 100;

  it('keeps the margins clear of the buttons TikTok and Reels stack on the right', () => {
    const fields = styleLine(buildAss(track, 'pop'));
    expect([fields[19], fields[20]]).toEqual(['90', '150']);
  });

  it('shrinks a word too long for the frame, in every style, and leaves a short one as it is', () => {
    for (const id of CAPTION_STYLE_IDS) {
      const ass = buildAss(LONG, id);
      const event = dialogues(ass).at(-1)!;
      const style = CAPTION_STYLES[id];
      const text = style.uppercase ? 'GESCHWINDIGKEITSBEGRENZUNG' : 'Geschwindigkeitsbegrenzung';
      expect(event, id).toMatch(/\\fscx\d+/);
      expect(textWidth(text, style) * lastScale(event), id).toBeLessThanOrEqual(840 + 2);
    }
    expect(dialogues(buildAss(track, 'classic'))[0]).not.toMatch(/\\fscx/);
  });

  it('shrinks the stamp of one word from its 180 % and every scale of a pop line alike', () => {
    const word = dialogues(buildAss(LONG, 'word'))[0]!;
    const [stamp, settle] = [...word.matchAll(/\\fscx(\d+)/g)].map((match) => Number(match[1]));
    expect(stamp! / settle!).toBeCloseTo(1.8, 1);
    expect(settle).toBeLessThan(100);
    const pop = dialogues(buildAss({ language: 'de', words: [{ text: 'die', start: 0, end: 0.3 }, ...LONG.words.map((w) => ({ ...w, start: 0.3, end: 1.5 }))] }, 'pop'));
    const long = pop.filter((event) => event.includes('GESCHWINDIGKEITSBEGRENZUNG'));
    expect(long).not.toHaveLength(0);
    for (const event of long) for (const match of event.matchAll(/\\fscx(\d+)/g)) expect(Number(match[1])).toBeLessThan(121);
  });
});
